import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";

import { answerProfilesApi, componentsApi } from "@/api/resources";
import type { AnswerProfileRead } from "@/api/types";
import { defaultsFromSchema, SchemaForm, type JsonSchema } from "@/components/SchemaForm";
import { Button } from "@/components/ui/Button";
import { Dialog } from "@/components/ui/Dialog";
import { queryKeys } from "@/lib/queryClient";
import { toast } from "@/lib/toast";

import { answerSystems, compactParams, parentChoices } from "./profiles";

const selectClass = "w-full rounded-md border border-line bg-paper px-3 py-1.5";

/**
 * Answer profile form generated from the registry. *Derive from* copies an existing profile's
 * parameters into the form and records it as the parent, so the new profile shows what
 * changed; `parent` opens the dialog already derived from one.
 */
export function AnswerProfileDialog({
  parent,
  onClose,
}: {
  parent?: AnswerProfileRead;
  onClose: () => void;
}) {
  const queryClient = useQueryClient();
  const [componentId, setComponentId] = useState<string | null>(null);
  const [parentId, setParentId] = useState<string>(parent?.id ?? "");
  const [params, setParams] = useState<Record<string, unknown> | null>(
    parent ? { ...parent.params } : null,
  );

  const components = useQuery({
    queryKey: queryKeys.components,
    queryFn: () => componentsApi.list(),
  });
  const profiles = useQuery({
    queryKey: queryKeys.answerProfiles,
    queryFn: answerProfilesApi.list,
  });

  const candidates = answerSystems(components.data ?? []);
  const component =
    candidates.find((item) =>
      parent
        ? item.versions?.some((version) => version.id === parent.component_version_id)
        : item.id === componentId,
    ) ?? candidates[0];
  const version =
    component?.versions?.find((item) => item.id === parent?.component_version_id) ??
    component?.versions?.find((item) => item.is_available) ??
    component?.versions?.[0];
  const schema = (version?.params_schema ?? { type: "object", properties: {} }) as JsonSchema;
  const effectiveParams = params ?? defaultsFromSchema(schema);
  const parents = parentChoices(profiles.data?.items ?? [], version?.id);

  const create = useMutation({
    mutationFn: () =>
      answerProfilesApi.create({
        component_version_id: version?.id ?? "",
        params: compactParams(effectiveParams),
        parent_profile_id: parentId || null,
      }),
    onSuccess: async (result) => {
      if (result.created) {
        toast.success(`Answer profile "${result.profile.name}" created.`);
      } else {
        toast.info(
          result.detail ?? `An identical profile already exists as "${result.profile.name}".`,
        );
      }
      await queryClient.invalidateQueries({ queryKey: queryKeys.answerProfiles });
      onClose();
    },
  });

  return (
    <Dialog
      title={parent ? `Derive from ${parent.name}` : "New answer profile"}
      onClose={onClose}
      wide
    >
      {candidates.length === 0 && components.isSuccess ? (
        <p className="text-sm text-ink-muted">No answer system is registered.</p>
      ) : (
        // A plain container: the params form generated by rjsf is a <form> itself.
        <div className="space-y-4">
          <div className="grid gap-4 sm:grid-cols-2">
            <label className="block text-sm">
              <span className="mb-1 block font-medium">Answer system</span>
              <select
                value={component?.id ?? ""}
                disabled={Boolean(parent)}
                onChange={(event) => {
                  setComponentId(event.target.value);
                  setParentId("");
                  setParams(null);
                }}
                className={selectClass}
              >
                {candidates.map((item) => (
                  <option key={item.id} value={item.id}>
                    {item.display_name}
                  </option>
                ))}
              </select>
            </label>
            <label className="block text-sm">
              <span className="mb-1 block font-medium">Derive from</span>
              <select
                value={parentId}
                onChange={(event) => {
                  const chosen = parents.find((item) => item.id === event.target.value);
                  setParentId(event.target.value);
                  if (chosen) setParams({ ...chosen.params });
                }}
                className={selectClass}
                data-testid="derive-from"
              >
                <option value="">Nothing: start from the defaults</option>
                {parents.map((item) => (
                  <option key={item.id} value={item.id}>
                    {item.name}
                  </option>
                ))}
              </select>
              <span className="mt-1 block text-xs text-ink-muted">
                Copies its parameters; the new profile then shows what changed from it.
              </span>
            </label>
          </div>

          {version && !version.is_available ? (
            <p className="rounded-md bg-danger/10 px-3 py-2 text-sm text-danger" role="alert">
              This answer system cannot run now: {version.unavailable_reason ?? "no reason given"}.
              The worker checks the model credentials when it starts.
            </p>
          ) : null}

          <div className="rounded-lg border border-line bg-paper p-4">
            <SchemaForm schema={schema} formData={effectiveParams} onChange={setParams} />
          </div>

          <p className="text-xs text-ink-muted">
            The profile is named after the system, the provider, the model and the temperature. The
            same parameters return the existing profile; a different prompt is a new one.
            Credentials are never parameters: the worker reads them from its environment.
          </p>
          <div className="flex justify-end gap-2">
            <Button type="button" variant="secondary" onClick={onClose}>
              Cancel
            </Button>
            <Button
              type="button"
              disabled={!version || !version.is_available || create.isPending}
              onClick={() => create.mutate()}
            >
              Create
            </Button>
          </div>
        </div>
      )}
    </Dialog>
  );
}
