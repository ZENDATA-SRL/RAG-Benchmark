import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";

import { componentsApi, embeddingProfilesApi, vectorStoreProfilesApi } from "@/api/resources";
import { defaultsFromSchema, SchemaForm, type JsonSchema } from "@/components/SchemaForm";
import { Button } from "@/components/ui/Button";
import { Dialog } from "@/components/ui/Dialog";
import { queryKeys } from "@/lib/queryClient";
import { toast } from "@/lib/toast";

export type ProfileKind = "embedder" | "vector_store";

const titles: Record<ProfileKind, string> = {
  embedder: "New embedding profile",
  vector_store: "New vector store profile",
};

/** Profile form generated from the registry: the params fields come from the version's schema. */
export function ProfileDialog({ kind, onClose }: { kind: ProfileKind; onClose: () => void }) {
  const queryClient = useQueryClient();
  const [componentId, setComponentId] = useState<string | null>(null);
  const [dimensions, setDimensions] = useState("");
  const [params, setParams] = useState<Record<string, unknown> | null>(null);

  const components = useQuery({
    queryKey: queryKeys.components,
    queryFn: () => componentsApi.list(),
  });

  const candidates = (components.data ?? []).filter((component) => component.type === kind);
  const component = candidates.find((item) => item.id === componentId) ?? candidates[0];
  const version =
    component?.versions?.find((item) => item.is_available) ?? component?.versions?.[0];
  const schema = (version?.params_schema ?? { type: "object", properties: {} }) as JsonSchema;
  const effectiveParams = params ?? defaultsFromSchema(schema);

  const create = useMutation({
    mutationFn: async () => {
      const common = { component_version_id: version?.id ?? "" };
      if (kind === "embedder") {
        const result = await embeddingProfilesApi.create({
          ...common,
          modality: "text",
          dimensions: dimensions ? Number(dimensions) : null,
          params: effectiveParams,
        });
        return { created: result.created, detail: result.detail, name: result.profile.name };
      }
      const result = await vectorStoreProfilesApi.create({
        ...common,
        index_params: effectiveParams,
      });
      return { created: result.created, detail: result.detail, name: result.profile.name };
    },
    onSuccess: async (result) => {
      if (result.created) {
        toast.success(`Profile "${result.name}" created.`);
      } else {
        toast.info(result.detail ?? `An identical profile already exists as "${result.name}".`);
      }
      await queryClient.invalidateQueries({
        queryKey: kind === "embedder" ? queryKeys.embeddingProfiles : queryKeys.vectorStoreProfiles,
      });
      onClose();
    },
  });

  return (
    <Dialog title={titles[kind]} onClose={onClose} wide>
      {candidates.length === 0 && components.isSuccess ? (
        <p className="text-sm text-ink-muted">No component of this type is registered.</p>
      ) : (
        // A plain container: the params form generated by rjsf is a <form> itself and forms
        // cannot nest.
        <div className="space-y-4">
          <div className="grid gap-4 sm:grid-cols-2">
            <label className="block text-sm">
              <span className="mb-1 block font-medium">Component</span>
              <select
                value={component?.id ?? ""}
                onChange={(event) => {
                  setComponentId(event.target.value);
                  setParams(null);
                }}
                className="w-full rounded-md border border-line bg-paper px-3 py-1.5"
              >
                {candidates.map((item) => (
                  <option key={item.id} value={item.id}>
                    {item.display_name}
                  </option>
                ))}
              </select>
            </label>
            {kind === "embedder" ? (
              <label className="block text-sm">
                <span className="mb-1 block font-medium">Dimensions (optional)</span>
                <input
                  type="number"
                  min={1}
                  value={dimensions}
                  onChange={(event) => setDimensions(event.target.value)}
                  placeholder="e.g. 1536"
                  className="w-full rounded-md border border-line bg-paper px-3 py-1.5"
                />
                <span className="mt-1 block text-xs text-ink-muted">
                  When set, a batch whose vectors have another size fails the build.
                </span>
              </label>
            ) : null}
          </div>

          <div className="rounded-lg border border-line bg-paper p-4">
            <SchemaForm schema={schema} formData={effectiveParams} onChange={setParams} />
          </div>

          <p className="text-xs text-ink-muted">
            The profile is named after the component, its version and the parameters that matter
            (model, dimensions, distance). The same parameters return the existing profile.
          </p>
          <div className="flex justify-end gap-2">
            <Button type="button" variant="secondary" onClick={onClose}>
              Cancel
            </Button>
            <Button
              type="button"
              disabled={!version || create.isPending}
              onClick={() => create.mutate()}
            >
              Create
            </Button>
          </div>
        </div>
      )}
    </Dialog>
  );
}
